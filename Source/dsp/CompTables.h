inline float lookup (const Table& t, float driveDb, float shape) noexcept
{
    const float dp = std::min (std::max ((driveDb + 24.0f) / 6.0f, 0.0f), (float) (numDrive - 1) - 1.0e-4f);
    const float sp = std::min (std::max (shape * (numShape - 1), 0.0f), (float) (numShape - 1) - 1.0e-4f);
    const int di = (int) dp, si = (int) sp;
    const float fd = dp - (float) di, fs = sp - (float) si;
    auto v = [&t] (int d, int s) { const float x = t[(size_t) d][(size_t) s]; return x > 0.0f ? std::log (x) : 0.0f; };
    const float a = v (di, si) + fs * (v (di, si + 1) - v (di, si));
    const float b = v (di + 1, si) + fs * (v (di + 1, si + 1) - v (di + 1, si));
    return std::exp (a + fd * (b - a));        // interpolated in the log domain
}
